#!/usr/bin/env python3
"""Installs (or removes) the weekday peak recording schedule on this Mac.

- A launchd agent runs scripts/run_record.py every weekday for the AM and PM
  peaks (see PEAKS), under `caffeinate -i` so the Mac doesn't idle-sleep
  mid-recording. If the Mac is asleep at the start time, launchd runs the job
  as soon as it wakes.
- Waking the Mac needs root, so this can't do it itself: it writes
  scripts/wake_schedule.sh with one `pmset schedule wake` per peak per
  weekday up to --until, for you to run once with sudo. The Mac must be on
  power for scheduled wakes.

    python scripts/install_recording_schedule.py            # install
    python scripts/install_recording_schedule.py --uninstall
"""
from __future__ import annotations

import argparse
import os
import plistlib
import subprocess
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
LABEL = "com.pulsecbd.recorder"
PLIST_PATH = Path.home() / "Library" / "LaunchAgents" / f"{LABEL}.plist"
WAKE_SCRIPT = REPO_ROOT / "scripts" / "wake_schedule.sh"
LOG_PATH = REPO_ROOT / "data" / "recordings" / "recorder.log"

# (start hour, start minute, minutes): AM peak 7-9 and PM peak 4:30-6:30,
# each with 5 minutes either side.
PEAKS = [(6, 55, 130), (16, 25, 130)]
WAKE_LEAD_MINUTES = 5


def _launchd_domain() -> str:
    return f"gui/{os.getuid()}"


def install(until: date) -> None:
    python = REPO_ROOT / ".venv" / "bin" / "python"
    if not python.exists():
        raise SystemExit(f"error: {python} not found -- set up the venv first (see README)")
    LOG_PATH.parent.mkdir(parents=True, exist_ok=True)

    # One launchd job, one StartCalendarInterval entry per (weekday, peak).
    # The recording length is the same for both peaks, so one command works.
    minutes = PEAKS[0][2]
    assert all(p[2] == minutes for p in PEAKS)
    plist = {
        "Label": LABEL,
        "ProgramArguments": [
            "/usr/bin/caffeinate", "-i",
            str(python), str(REPO_ROOT / "scripts" / "run_record.py"), "--minutes", str(minutes),
        ],
        "WorkingDirectory": str(REPO_ROOT),
        "StartCalendarInterval": [
            {"Weekday": weekday, "Hour": hour, "Minute": minute}
            for weekday in range(1, 6)
            for hour, minute, _ in PEAKS
        ],
        "StandardOutPath": str(LOG_PATH),
        "StandardErrorPath": str(LOG_PATH),
    }
    PLIST_PATH.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["launchctl", "bootout", _launchd_domain(), str(PLIST_PATH)], capture_output=True)
    with open(PLIST_PATH, "wb") as f:
        plistlib.dump(plist, f)
    subprocess.run(["launchctl", "bootstrap", _launchd_domain(), str(PLIST_PATH)], check=True)
    print(f"installed {PLIST_PATH}")
    print(f"recording log: {LOG_PATH}")

    _write_wake_script(until)
    print(f"\nwrote {WAKE_SCRIPT} -- run it once so the Mac wakes for each peak:")
    print(f"    sudo sh {WAKE_SCRIPT.relative_to(REPO_ROOT)}")


def _write_wake_script(until: date) -> None:
    lines = [
        "#!/bin/sh",
        "# Generated by scripts/install_recording_schedule.py -- wakes the Mac",
        f"# {WAKE_LEAD_MINUTES} minutes before each weekday peak recording. Run with sudo.",
        "# Check with: pmset -g sched",
        "set -e",
    ]
    now = datetime.now()
    day = now.date()
    while day <= until:
        if day.weekday() < 5:
            for hour, minute, _ in PEAKS:
                wake = datetime(day.year, day.month, day.day, hour, minute) - timedelta(minutes=WAKE_LEAD_MINUTES)
                if wake > now:
                    lines.append(f'pmset schedule wake "{wake:%m/%d/%y %H:%M:%S}"')
        day += timedelta(days=1)
    WAKE_SCRIPT.write_text("\n".join(lines) + "\n", encoding="utf-8")


def uninstall() -> None:
    subprocess.run(["launchctl", "bootout", _launchd_domain(), str(PLIST_PATH)], capture_output=True)
    if PLIST_PATH.exists():
        PLIST_PATH.unlink()
    print(f"removed {PLIST_PATH}")
    print("scheduled wakes (if any) stay until they pass; list them with: pmset -g sched")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--uninstall", action="store_true")
    parser.add_argument("--until", type=date.fromisoformat, default=date(2026, 11, 6),
                        help="last day to schedule wakes for (default: showcase day)")
    args = parser.parse_args()
    if args.uninstall:
        uninstall()
    else:
        install(args.until)
    return 0


if __name__ == "__main__":
    sys.exit(main())
